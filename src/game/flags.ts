// Криптослой сайта: кошелёк, покупка DC за ETH, маркетплейс, продажа уток, знак Pons Family и
// упоминания сети в текстах. По умолчанию ВКЛЮЧЁН, прячется переменной окружения
// `VITE_CRYPTO=off` (Vercel: Settings, Environment Variables, затем redeploy).
//
// Игровая часть от флага не зависит вообще: DC, дейли, рулетка, сундуки, аксессуары, брид,
// квесты, обе миниигры и таблицы работают под гостевой сессией, без кошелька и без подписи.
// Поэтому выключенный флаг ничего не ломает, он только прячет то, что связано с деньгами.
export const CRYPTO_ON = import.meta.env.VITE_CRYPTO !== "off";

// Маркетплейс уток за DC: кнопка Market в шапке и окно `dcmarket`. По умолчанию ВЫКЛЮЧЕН,
// показывается переменной окружения `VITE_DCMARKET=on`. Лоты, эскроу и edge fn `market-dc`
// на сервере остаются как есть, прячется только вход в них из интерфейса.
export const DC_MARKET_ON = import.meta.env.VITE_DCMARKET === "on";
